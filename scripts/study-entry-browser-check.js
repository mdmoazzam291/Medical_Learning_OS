import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_URL || 'playwright');
const browser = await chromium.launch({ headless: true });
const origin = process.env.PREVIEW_ORIGIN || 'http://127.0.0.1:3000';
const errors = [];
const question = { questionVersionId: 'interface:entry@1', conceptId: 'interface:entry', stem: 'Synthetic interface question: choose the first option.', options: [{ optionId: 'a', text: 'First option' }, { optionId: 'b', text: 'Second option' }] };
const receipt = { selectedOptionId: 'a', answerOptionId: 'a', explanation: 'Nonclinical interface fixture.', sources: [], event: { eventId: 'entry-fixture', correct: true } };
try {
  for (const [name, width, height] of [['phone', 390, 844], ['tablet', 820, 1180], ['desktop', 1440, 1000]]) {
    const context = await browser.newContext({ viewport: { width, height } });
    await context.addInitScript(() => localStorage.setItem('mlos-supabase-auth-v1', JSON.stringify({ accessToken: 'jwt-test', refreshToken: 'refresh-test', expiresAt: 2100000000, user: { id: '11111111-1111-4111-8111-111111111111', email: 'fixture@example.invalid', emailConfirmedAt: '2026-09-29T00:00:00Z' } })));
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    const writes = [];
    const reads = [];
    let revisionMode = 'ready';
    let progressUnavailable = false;
    let questionsUnavailable = false;
    let startMode = 'new';
    let savedReceipt = null;
    let closed = false;
    let releaseStart;
    let startGate = null;
    const session = id => ({ sessionId: id, position: 0, total: 1, closed, question: closed ? null : question, receipt: closed ? null : savedReceipt, memoryJudgment: null });
    await page.route('https://iyapppmeieqhflnzslao.supabase.co/**', async route => {
      const request = route.request();
      const path = new URL(request.url()).pathname.split('/functions/v1/study-api')[1];
      const method = request.method();
      const fulfill = (body, status = 200) => route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) });
      if (method === 'GET') reads.push(path); else writes.push({ path, body: request.postDataJSON() });
      if (path === '/questions') return fulfill(questionsUnavailable ? { error: 'questions_unavailable' } : { questions: [question] }, questionsUnavailable ? 503 : 200);
      if (path === '/progress') return fulfill(progressUnavailable ? { error: 'progress_unavailable' } : { attempts: 2, correct: 1 }, progressUnavailable ? 503 : 200);
      if (path === '/revision/due') return fulfill(revisionMode === 'unavailable' ? { error: 'revision_unavailable' } : { dueCount: revisionMode === 'ready' ? 2 : 0, unseenCount: 0, nextDueAt: '2026-10-02T00:00:00Z', items: [] }, revisionMode === 'unavailable' ? 503 : 200);
      if (path?.startsWith('/exam-simulator/readiness')) return fulfill({ eligibleUniqueQuestions: 1, requiredUniqueQuestions: 180, shortage: 179, ready: false });
      if (path === '/study-now/start') {
        if (startGate) await startGate;
        if (startMode === 'failure') return fulfill({ error: 'start_unavailable' }, 503);
        return fulfill({ plan: { resumedExisting: startMode === 'resumed' }, session: startMode === 'empty' ? null : session('entry-session') });
      }
      if (path === '/sessions' && method === 'POST') return fulfill(session('qbank-session'));
      if (path === '/sessions/entry-session' || path === '/sessions/qbank-session') return fulfill(session(path.split('/').at(-1)));
      if (path?.endsWith('/summary')) return fulfill({ contractId: 'study-session-summary-v1', sessionId: path.split('/').at(-2), closed: true, selectedCount: 1, answeredCount: 1, correctCount: 1, incorrectCount: 0, unansweredCount: 0, completedAllSelected: true, concepts: [], revision: { available: false } });
      return fulfill({ error: 'not_found' }, 404);
    });
    await page.goto(origin + '/web/medical.html');
    await page.getByRole('button', { name: 'Open 20 min session' }).waitFor();
    assert.equal(await page.locator('button.primary').count(), 1, 'one primary session action');
    assert.equal(await page.locator('.question-browser-list').getAttribute('open'), null);
    await page.getByRole('button', { name: '30 min', exact: true }).click();
    await page.reload();
    await page.getByRole('button', { name: 'Open 30 min session' }).waitFor();
    assert.equal(await page.getByRole('button', { name: '30 min', exact: true }).getAttribute('aria-pressed'), 'true');
    await page.locator('.question-browser-list > summary').click();
    await page.getByRole('heading', { name: question.stem, exact: true }).waitFor();
    await page.locator('.question-browser-list > summary').click();
    assert.deepEqual(writes, [], 'duration, browsing and reload cannot start a session');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, name + ' entry overflow');
    await page.evaluate(() => { document.activeElement.blur(); window.scrollTo(0, 0); });
    if (process.env.SCREENSHOT_DIR) await page.screenshot({ path: process.env.SCREENSHOT_DIR + '/ux-study-entry-' + name + '.png', fullPage: true, animations: 'disabled' });
    startGate = new Promise(resolve => { releaseStart = resolve; });
    await page.getByRole('button', { name: 'Open 30 min session' }).click();
    await page.getByRole('heading', { name: 'Opening your session…' }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Open 30 min session' }).isDisabled(), true);
    assert.equal(await page.getByRole('button', { name: 'Open QBank session' }).isDisabled(), true);
    releaseStart(); startGate = null;
    await page.getByText('New recommended session', { exact: false }).waitFor();
    assert.equal(new URL(page.url()).searchParams.get('resume'), 'entry-session');
    assert.equal(writes.length, 1);
    assert.equal(writes[0].body.availableMinutes, 30);
    questionsUnavailable = true;
    reads.length = 0;
    await page.reload();
    await page.getByText('Question 1 of 1', { exact: false }).waitFor();
    assert.deepEqual(reads, ['/sessions/entry-session'], 'session restoration does not depend on overview reads');
    assert.equal(writes.length, 1, 'reload only reads the current saved session');
    questionsUnavailable = false;
    startMode = 'resumed'; savedReceipt = receipt;
    await page.goto(origin + '/web/medical.html?studyNow=10');
    await page.getByText('Continuing saved session', { exact: false }).waitFor();
    await page.getByRole('heading', { name: 'Correct.', exact: true }).waitFor();
    await page.reload();
    await page.getByRole('heading', { name: 'Correct.', exact: true }).waitFor();
    assert.equal(writes.length, 2, 'saved-answer reload cannot replay start, answer or rating');
    closed = true;
    await page.reload();
    await page.getByRole('heading', { name: 'This session', exact: true }).waitFor();
    assert.equal(new URL(page.url()).searchParams.get('summary'), 'entry-session');
    closed = false; savedReceipt = null;
    revisionMode = 'unavailable'; progressUnavailable = true;
    await page.goto(origin + '/web/medical.html');
    await page.getByRole('heading', { name: 'Schedule temporarily unavailable.' }).waitFor();
    assert.match(await page.locator('.study-snapshot').innerText(), /—\s*Saved attempts/);
    assert.equal(await page.getByRole('button', { name: /Open \d+ min session/ }).count(), 0);
    await page.getByRole('button', { name: 'Open QBank session' }).click();
    await page.getByText('Session opened', { exact: false }).waitFor();
    assert.equal(new URL(page.url()).searchParams.get('resume'), 'qbank-session');
    await page.reload();
    await page.getByText('Question 1 of 1', { exact: false }).waitFor();
    assert.equal(writes.length, 3);
    revisionMode = 'upcoming'; progressUnavailable = false;
    await page.goto(origin + '/web/medical.html');
    await page.getByRole('heading', { name: 'Your scheduled reviews are up to date.' }).waitFor();
    assert.equal(await page.getByRole('button', { name: /Open \d+ min session/ }).count(), 0);
    assert.equal(writes.length, 3, 'upcoming reviews are never pulled early');
    revisionMode = 'ready'; startMode = 'failure';
    await page.reload();
    await page.getByRole('button', { name: 'Open 30 min session' }).click();
    await page.getByRole('heading', { name: 'Study could not open.' }).waitFor();
    await page.reload();
    await page.getByRole('button', { name: 'Open 30 min session' }).waitFor();
    assert.equal(writes.length, 4, 'failed start does not retry automatically on reload');
    startMode = 'empty';
    await page.getByRole('button', { name: 'Open 30 min session' }).click();
    await page.getByRole('alert').filter({ hasText: 'Nothing is currently recommended' }).waitFor();
    assert.equal(new URL(page.url()).searchParams.has('resume'), false);
    assert.deepEqual(writes.map(item => item.path), ['/study-now/start', '/study-now/start', '/sessions', '/study-now/start', '/study-now/start']);
    questionsUnavailable = true;
    await page.goto(origin + '/web/medical.html');
    await page.getByRole('heading', { name: 'Study temporarily unavailable.' }).waitFor();
    assert.equal(await page.getByText('No published medical questions.', { exact: true }).count(), 0, 'read failure is not an empty catalog');
    assert.equal(await page.getByRole('button', { name: /Open .* session/ }).count(), 0);
    assert.equal(writes.length, 5);
    await context.close();
  }
  assert.deepEqual(errors, []);
  console.log('Responsive single-action Study entry, duration/browse no-write checks, honest resume, direct GET reload, outages, busy states and explicit failure retry passed');
} finally { await browser.close(); }
